"""Generate per-node bootstrap shell scripts for kubeadm prerequisites.

Supports two OS families:
- debian: apt-based (Ubuntu 22.04/24.04, Debian 12)
- redhat: dnf-based with EPEL enabled (RHEL 8/9, Rocky, Alma, CentOS Stream)

The produced script is idempotent and leaves the node ready for `kubeadm join`
or `kubeadm init`: kernel modules + sysctl, container runtime (containerd),
kubelet/kubeadm/kubectl pinned to the project's K8s version, and swap off.
"""

from __future__ import annotations


def _common_header(k8s_version: str) -> str:
    return f"""#!/usr/bin/env bash
set -euo pipefail

# Generated by cloud-ictneo console for Kubernetes v{k8s_version}
# This script is idempotent and safe to re-run.

K8S_VERSION="{k8s_version}"
K8S_REPO_VERSION="v${{K8S_VERSION}}"

echo "==> disabling swap"
sudo swapoff -a
sudo sed -i.bak '/ swap / s/^\\(.*\\)$/#\\1/g' /etc/fstab

echo "==> loading kernel modules"
sudo tee /etc/modules-load.d/k8s.conf >/dev/null <<EOF
overlay
br_netfilter
EOF
sudo modprobe overlay
sudo modprobe br_netfilter

echo "==> sysctl tuning"
sudo tee /etc/sysctl.d/k8s.conf >/dev/null <<EOF
net.bridge.bridge-nf-call-iptables  = 1
net.bridge.bridge-nf-call-ip6tables = 1
net.ipv4.ip_forward                 = 1
EOF
sudo sysctl --system >/dev/null
"""


def _debian_body() -> str:
    return """
echo "==> apt: installing prerequisites"
sudo apt-get update -y
sudo apt-get install -y apt-transport-https ca-certificates curl gpg software-properties-common

echo "==> apt: installing containerd"
sudo apt-get install -y containerd
sudo mkdir -p /etc/containerd
containerd config default | sudo tee /etc/containerd/config.toml >/dev/null
sudo sed -i 's/SystemdCgroup = false/SystemdCgroup = true/' /etc/containerd/config.toml
sudo systemctl restart containerd
sudo systemctl enable containerd

echo "==> apt: adding kubernetes repository"
sudo mkdir -p /etc/apt/keyrings
curl -fsSL "https://pkgs.k8s.io/core:/stable:/${K8S_REPO_VERSION}/deb/Release.key" \\
  | sudo gpg --dearmor --yes -o /etc/apt/keyrings/kubernetes-apt-keyring.gpg
echo "deb [signed-by=/etc/apt/keyrings/kubernetes-apt-keyring.gpg] https://pkgs.k8s.io/core:/stable:/${K8S_REPO_VERSION}/deb/ /" \\
  | sudo tee /etc/apt/sources.list.d/kubernetes.list >/dev/null

echo "==> apt: installing kubelet / kubeadm / kubectl"
sudo apt-get update -y
sudo apt-get install -y kubelet kubeadm kubectl
sudo apt-mark hold kubelet kubeadm kubectl

sudo systemctl enable --now kubelet
"""


def _redhat_body() -> str:
    return """
echo "==> dnf: enabling EPEL"
sudo dnf install -y epel-release || sudo dnf install -y \\
  "https://dl.fedoraproject.org/pub/epel/epel-release-latest-$(rpm -E %rhel).noarch.rpm"

echo "==> dnf: installing prerequisites"
sudo dnf install -y curl gnupg2 ca-certificates tar iproute-tc policycoreutils-python-utils

echo "==> setting SELinux to permissive (kubelet requirement)"
sudo setenforce 0 || true
sudo sed -i 's/^SELINUX=enforcing$/SELINUX=permissive/' /etc/selinux/config

echo "==> dnf: installing containerd"
sudo dnf config-manager --add-repo https://download.docker.com/linux/centos/docker-ce.repo
sudo dnf install -y containerd.io
sudo mkdir -p /etc/containerd
containerd config default | sudo tee /etc/containerd/config.toml >/dev/null
sudo sed -i 's/SystemdCgroup = false/SystemdCgroup = true/' /etc/containerd/config.toml
sudo systemctl restart containerd
sudo systemctl enable containerd

echo "==> dnf: adding kubernetes repository"
sudo tee /etc/yum.repos.d/kubernetes.repo >/dev/null <<EOF
[kubernetes]
name=Kubernetes
baseurl=https://pkgs.k8s.io/core:/stable:/${K8S_REPO_VERSION}/rpm/
enabled=1
gpgcheck=1
gpgkey=https://pkgs.k8s.io/core:/stable:/${K8S_REPO_VERSION}/rpm/repodata/repomd.xml.key
exclude=kubelet kubeadm kubectl cri-tools kubernetes-cni
EOF

echo "==> dnf: installing kubelet / kubeadm / kubectl"
sudo dnf install -y --disableexcludes=kubernetes kubelet kubeadm kubectl

echo "==> opening firewall ports (control-plane + worker)"
if systemctl is-active --quiet firewalld; then
  sudo firewall-cmd --permanent --add-port=6443/tcp || true
  sudo firewall-cmd --permanent --add-port=2379-2380/tcp || true
  sudo firewall-cmd --permanent --add-port=10250/tcp || true
  sudo firewall-cmd --permanent --add-port=10251/tcp || true
  sudo firewall-cmd --permanent --add-port=10252/tcp || true
  sudo firewall-cmd --permanent --add-port=10255/tcp || true
  sudo firewall-cmd --permanent --add-port=30000-32767/tcp || true
  sudo firewall-cmd --reload || true
fi

sudo systemctl enable --now kubelet
"""


def _footer() -> str:
    return """
echo
echo "==> bootstrap complete"
echo "Kubernetes packages installed:"
kubeadm version -o short
kubectl version --client -o yaml 2>/dev/null | head -n 5 || kubectl version --client
"""


def generate_bootstrap(os_family: str, k8s_version: str) -> str:
    if os_family == "debian":
        body = _debian_body()
    elif os_family == "redhat":
        body = _redhat_body()
    else:
        raise ValueError(f"Unsupported os_family: {os_family}")
    return _common_header(k8s_version) + body + _footer()
